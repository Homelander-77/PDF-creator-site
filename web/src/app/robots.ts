import type { MetadataRoute } from 'next';
import { SITE_URL } from '@/lib/site';

/**
 * robots.txt.
 *
 * В Next это не файл в public, а маленький роут: адрес /robots.txt Next
 * отдаёт сам, собирая содержимое из того, что вернёт эта функция. Плюс в
 * том, что домен сюда подставляется из переменной окружения, а не забивается
 * руками в текстовый файл, про который потом все забывают.
 *
 * Закрыт здесь только кабинет — он за авторизацией, и поисковику там
 * показывать нечего.
 *
 * А вот страницы входа, регистрации и всего, что приходит в письмах,
 * намеренно НЕ закрыты запретом. Запрет в robots.txt означает «не заходи»,
 * то есть робот не прочитает и стоящий на странице запрет на индексацию —
 * и ссылка всё равно может всплыть в выдаче, только без описания. Поэтому
 * на них стоит noindex в самой странице (см. соседние layout.tsx), а сюда
 * они не попадают: робот должен зайти и увидеть запрет своими глазами.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      allow: '/',
      disallow: ['/dashboard'],
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
