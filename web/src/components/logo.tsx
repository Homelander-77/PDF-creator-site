/**
 * Фирменный знак.
 *
 * Один компонент на шапку, подвал и кабинет. До этого в трёх местах стоял
 * контурный значок документа, а в иконке вкладки — совсем другой знак:
 * плитка с градиентом и лист. Разные логотипы на одной странице человек
 * замечает раньше, чем любую из наших оптимизаций.
 *
 * Плитка сделана фоном обычного span, а не градиентом внутри SVG. В SVG
 * градиент требует <defs> с идентификатором, а знак встречается на странице
 * несколько раз — одинаковые идентификаторы в одном документе недопустимы.
 * Здесь этой проблемы просто нет.
 *
 * Цвета зафиксированы, а не взяты из темы: знак должен читаться одинаково
 * и на светлом, и на тёмном, как и иконка вкладки.
 */
export function Logo({ size = 28 }: { size?: number }) {
  return (
    <span
      aria-hidden
      className="grid shrink-0 place-items-center bg-gradient-to-br from-[#6b5cf0] to-[#2ad4e6]"
      style={{
        width: size,
        height: size,
        // Скругление держим пропорциональным: на 24 и на 40 пикселях
        // фиксированные 8px выглядят по-разному.
        borderRadius: Math.round(size * 0.235),
      }}
    >
      <svg
        width={size}
        height={size}
        viewBox="0 0 64 64"
        style={{ display: 'block' }}
      >
        {/* Лист */}
        <path
          d="M16 18a6 6 0 0 1 6-6h14l12 12v22a6 6 0 0 1-6 6H22a6 6 0 0 1-6-6z"
          fill="#ffffff"
        />
        {/* Загнутый угол */}
        <path d="M36 12l12 12h-7a5 5 0 0 1-5-5z" fill="#0b1020" opacity="0.22" />
      </svg>
    </span>
  );
}
